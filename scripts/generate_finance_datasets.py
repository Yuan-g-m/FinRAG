def write_rag_docs():
    for source, content in RAG_DOCS.items():
        target_dir = DATA_DIR / f"{source}_data"
        target_dir.mkdir(parents=True, exist_ok=True)
        (target_dir / f"{source}基础知识.md").write_text(content, encoding="utf-8")


def write_faq_csv():
    lines = ["领域,问题,答案"]
    for domain, question, answer in FAQ_ITEMS:
        answer = answer.replace(",", "，")
        lines.append(f"{domain},{question},{answer}")
    FAQ_CSV.parent.mkdir(parents=True, exist_ok=True)
    FAQ_CSV.write_text("\n".join(lines), encoding="utf-8")


def build_classification_lines(count_per_class=500):
    lines = []
    suffix_templates = ["", "，请简要说明。", "，请给出要点。", "？", "，请用中文回答。"]

    for i in range(count_per_class):
        base = PROFESSIONAL_QUERIES[i % len(PROFESSIONAL_QUERIES)]
        suffix = suffix_templates[(i // len(PROFESSIONAL_QUERIES)) % len(suffix_templates)]
        query = base.rstrip("？") + suffix if suffix else base
        lines.append(json.dumps({"query": query, "label": "专业咨询"}, ensure_ascii=False))

    for i in range(count_per_class):
        base = GENERIC_QUERIES[i % len(GENERIC_QUERIES)]
        suffix = suffix_templates[(i // len(GENERIC_QUERIES)) % len(suffix_templates)]
        query = base.rstrip("。") + suffix if suffix else base
        lines.append(json.dumps({"query": query, "label": "通用知识"}, ensure_ascii=False))
    return lines


